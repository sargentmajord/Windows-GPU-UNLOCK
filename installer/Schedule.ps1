# When the unlock is applied after the first one (plan requirements 22, 24, 26, 27, 28).
#  - Always: the shortcut "Unlock my GPU on next boot" (asks for administrator approval, queues one unlock, offers the restart).
#  - Only with automatic mode (Extra 1) and only after an explicit opt-in: a Windows startup task that queues the next unlock at every start
#    (internal-boot\Set-UnlockSchedule.ps1 -Mode EveryBoot). Its circuit breaker reads automatic-mode run folders, so it cannot be used with
#    the manual program.
# The permanent firmware boot order and the Windows boot entry are never changed. Needs State.ps1, Ui.ps1, Capture.ps1 (Get-RepoRoot),
# BuildTest.ps1 (New-ScriptCall), Backup.ps1.

$script:ShortcutName = 'Unlock my GPU on next boot'

# --- system calls (replaceable in tests) ---
function Get-SysDesktopPath { [Environment]::GetFolderPath('Desktop') }
function Get-SysStartMenuPath { [Environment]::GetFolderPath('CommonPrograms') }   # C:\ProgramData\Microsoft\Windows\Start Menu\Programs, changeable only by administrators
function Get-SysDataRoot { Join-Path $env:ProgramData 'WindowsGPUUnlock' }
function Invoke-SysScheduleScript([string]$CommandText) {
 $ErrorActionPreference = 'Continue'
 $o = & powershell.exe -NoProfile -ExecutionPolicy Bypass -Command $CommandText 2>&1
 [pscustomobject]@{ Code = $LASTEXITCODE; Output = ($o | Out-String) }
}
# Creates the .lnk with the "Run as administrator" flag set, so Windows shows its own approval prompt when it is opened.
function Invoke-SysCreateShortcut([string]$LinkPath, [string]$Target, [string]$Arguments, [string]$Description) {
 $sh = New-Object -ComObject WScript.Shell
 $l = $sh.CreateShortcut($LinkPath)
 $l.TargetPath = $Target; $l.Arguments = $Arguments; $l.Description = $Description; $l.WindowStyle = 1
 $l.IconLocation = "$env:SystemRoot\System32\shell32.dll,27"
 $l.Save()
 $b = [IO.File]::ReadAllBytes($LinkPath)
 $b[0x15] = $b[0x15] -bor 0x20          # SLDF_RUNAS_USER in the link flags
 [IO.File]::WriteAllBytes($LinkPath, $b)
}
function Test-ShortcutRunsAsAdmin([string]$LinkPath) { $b = [IO.File]::ReadAllBytes($LinkPath); (($b[0x15] -band 0x20) -ne 0) }

# --- the script behind the shortcut ---
function Get-LookupCode { Get-Content -LiteralPath (Join-Path (Get-RepoRoot) 'internal-boot\UnlockEntryLookup.ps1') -Raw }

function Get-ShortcutScriptText([ValidateSet('manual', 'automatic')][string]$Mode) {
 $what = if ($Mode -eq 'manual') {
  @("Say 'At the next start the unlock program waits for you to press U once. Esc, or 30 seconds with no key, cancels it and Windows simply starts.'")
 } else {
  @("Say 'At the next start the unlock runs by itself; no key is needed. Windows then starts.'")
 }
 $lookup = Get-LookupCode
 $security = $script:SecurityCheckCode
 @"
# Generated by the Windows GPU UNLOCK installer. Queues ONE unlock for the next start. It changes no permanent boot setting.
`$ErrorActionPreference = 'Stop'
`$label = 'GPUUNLOCK'
function Say([string]`$Text) { Write-Host `$Text }
$security
$lookup
try {
 # This script runs as administrator: refuse if it or its folder can be changed by anyone but the administrators or SYSTEM.
 `$problems = @(Get-SecurityProblems `$PSCommandPath) + @(Get-SecurityProblems (Split-Path -Parent `$PSCommandPath))
 if (`$problems.Count) { throw ('This script or its folder can be changed by ordinary users, so it will not run: ' + (`$problems -join '; ')) }
 `$who = [Security.Principal.WindowsPrincipal][Security.Principal.WindowsIdentity]::GetCurrent()
 if (-not `$who.IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)) { throw 'Administrator rights are needed (open this from the shortcut and approve the Windows prompt).' }
 `$secure = `$null; try { `$secure = Confirm-SecureBootUEFI } catch { }
 if (`$secure -ne `$false) { throw 'Secure Boot is not confirmed off, so the firmware would refuse the unlock program.' }
 `$id = Find-UnlockEntry
 & bcdedit.exe /set '{fwbootmgr}' bootsequence `$id | Out-Null
 if (`$LASTEXITCODE -ne 0) { throw 'Windows could not queue the one-time boot.' }
 Say ''
 Say 'One unlock is queued for the next start.'
 $($what -join "`r`n ")
 Say 'If the screen freezes: hold the power button until the PC turns off, then power on. Windows then starts normally.'
 Say 'The unlock lasts until the PC is powered off or goes to sleep; run this shortcut again after that.'
 Say ''
 `$a = (Read-Host 'Restart now? Save and close your work first (Y/N)').Trim().ToUpper()
 if (`$a -eq 'Y') {
  & shutdown.exe /r /t 30 /c 'Windows GPU Unlock: restarting to apply the unlock.'
  Say 'The PC restarts in 30 seconds. To cancel, type:  shutdown /a'
 } else {
  Say 'Restart when you are ready. The unlock stays queued for the next start.  To cancel it, run the installer and choose Roll back.'
 }
} catch {
 Say ('Could not queue the unlock: ' + `$_.Exception.Message)
 Say 'Nothing was changed.'
}
Say ''
[void](Read-Host 'Press Enter to close this window')
"@
}

# Writes the script into the protected data folder and the shortcut into the all-users Start menu (only administrators can change that
# folder). A copy on the desktop is optional: any program running as the user can edit a desktop shortcut and so change what an
# approved click runs as administrator. Every file is written journaled, and checked afterwards.
function New-UnlockShortcut($State, [ValidateSet('manual', 'automatic')][string]$Mode = 'manual', [switch]$Desktop, [switch]$DryRun) {
 $dataRoot = Get-SysDataRoot
 $scriptPath = Join-Path $dataRoot 'Unlock-Next-Boot.ps1'
 $name = $script:ShortcutName + '.lnk'
 $links = @(Join-Path (Get-SysStartMenuPath) $name)
 if ($Desktop) { $links += Join-Path (Get-SysDesktopPath) $name }
 if ($DryRun) { Write-Plain "DRYRUN: create the script $scriptPath and the shortcut '$($script:ShortcutName)' in the Start menu$(if ($Desktop) { ' and on the desktop' })"; return [pscustomobject]@{ Script = $scriptPath; Links = $links } }
 $text = Get-ShortcutScriptText $Mode
 $e = $null
 [void][System.Management.Automation.Language.Parser]::ParseInput($text, [ref]$null, [ref]$e)
 if ($e.Count) { throw ('The generated shortcut script is not valid PowerShell: ' + $e[0].Message) }
 $psExe = Join-Path $env:SystemRoot 'System32\WindowsPowerShell\v1.0\powershell.exe'
 [void](Invoke-JournaledChange -Phase 'schedule' -Action 'write the next-boot unlock script' -Target $scriptPath -Previous ([ordered]@{ Existed = (Test-Path -LiteralPath $scriptPath) }) -Undo 'delete it' -Do {
  Write-SecureFile $scriptPath $text ([Text.UTF8Encoding]::new($true))
 })
 foreach ($link in $links) {
  $isStart = ($link -eq $links[0])
  [void](Invoke-JournaledChange -Phase 'schedule' -Action $(if ($isStart) { 'create the Start menu shortcut' } else { 'create the desktop shortcut' }) -Target $link -Previous ([ordered]@{ Existed = (Test-Path -LiteralPath $link) }) -Undo 'delete it if it is still the shortcut the installer made' -Do {
   Invoke-SysCreateShortcut $link $psExe ('-NoProfile -ExecutionPolicy Bypass -File "{0}"' -f $scriptPath) 'Queue one GPU unlock for the next start (asks for administrator approval)'
   if ($isStart) {
    Invoke-SysIcacls @($link, '/setowner', '*S-1-5-32-544', '/Q')
    $p = @(Get-SecurityProblems $link) + @(Get-SecurityProblems (Split-Path -Parent $link))
    if ($p.Count) { Remove-Item -LiteralPath $link -Force -ErrorAction SilentlyContinue; throw ('The Start menu shortcut can be changed by ordinary users, so it was removed: ' + ($p -join '; ')) }
   }
  })
 }
 [pscustomobject]@{ Script = $scriptPath; Links = $links }
}

# --- every boot (needs automatic mode) ---
function Show-EveryBootWarning {
 Write-Plain ''
 Write-Plain 'Unlock at every start (optional, off unless you say yes):'
 Write-Plain '  - What runs: a Windows startup task (as the system account) runs a small script at every Windows start. It checks that Secure Boot and Fast Startup are still off'
 Write-Plain '    and that the boot partition is there, then queues one unlock for the next start. The permanent boot order and the Windows boot entry are never changed.'
 Write-Plain '  - If a check fails at the screen before Windows, the screen freezes. Hold the power button until the PC turns off, then power on; Windows then starts normally.'
 Write-Plain '    No BIOS or boot menu is needed. After a failed or unfinished run the task stops queuing by itself and says so.'
 Write-Plain '  - Windows Fast Startup is turned off (its old value is saved), because a "Shut down" with Fast Startup on is not a cold start.'
 Write-Plain '  - A backup of the boot configuration is made first. To undo all of it, choose Roll back in the installer.'
}

# Asks the opt-in question. The default is No: only an explicit Y turns it on.
function Ask-EveryBoot {
 Show-EveryBootWarning
 Ask-YesNo 'Unlock at every start?'
}

# Registers the startup task through the project's own script (which backs up the boot configuration, saves and turns off Fast Startup).
function Enable-EveryBoot($State, [switch]$DryRun) {
 if (-not ($State.Contains('Automatic') -and $State.Automatic -and $State.Automatic.Active)) { throw 'Unlock at every start needs automatic mode, which is not active.' }
 if (-not $State.Contains('Unlock') -or -not $State.Unlock -or -not $State.Unlock.Applied) { throw 'Unlock at every start is offered only after an unlock has been verified.' }
 $call = New-ScriptCall (Join-Path (Get-RepoRoot) 'internal-boot\Set-UnlockSchedule.ps1') ([ordered]@{ Mode = 'EveryBoot'; DryRun = [bool]$DryRun })
 if ($DryRun) { Write-Plain 'DRYRUN: register the startup task through Set-UnlockSchedule.ps1 -Mode EveryBoot'; return }
 [void](Invoke-JournaledChange -Phase 'schedule' -Action 'unlock at every start (startup task, Fast Startup off)' -Target 'WindowsGPUUnlock-ArmNextBoot' `
  -Previous ([ordered]@{ FastStartup = (Get-SysFastStartup) }) -Undo 'Set-UnlockSchedule.ps1 -Mode Off (removes the task, restores Fast Startup)' -Do {
   $r = Invoke-SysScheduleScript $call
   if ($r.Code -ne 0) { throw ('Setting up the startup task failed: ' + $r.Output) }
  })
 $State.Schedule = [ordered]@{ Mode = 'EveryBoot'; Set = (Get-Date).ToString('o') }
}

# Removes the startup task and restores Fast Startup (also what Roll back uses).
function Disable-EveryBoot([switch]$DryRun) {
 $call = New-ScriptCall (Join-Path (Get-RepoRoot) 'internal-boot\Set-UnlockSchedule.ps1') ([ordered]@{ Mode = 'Off'; DryRun = [bool]$DryRun })
 $r = Invoke-SysScheduleScript $call
 if ($r.Code -ne 0) { throw ('Turning off the startup task failed: ' + $r.Output) }
 $r.Output
}
